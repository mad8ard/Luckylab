#!/usr/bin/env node
// Convert public CSV datasets into JS modules so Vite owns data delivery.
// This avoids static hosting rewrite rules treating CSV files as SPA routes.
//
// 注意：这里原地更新 src/data/generated，不再重命名整个目录。
// Windows + Vite watcher 会持有目录句柄，目录 rename 会触发 EPERM。

import { mkdir, readdir, readFile, rename, rm, unlink, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const DATA_DIR = join(ROOT, 'src', 'data')
const SOURCE_DIR = join(ROOT, 'public', 'data')
const TARGET_DIR = join(DATA_DIR, 'generated')
const CSV_MODULE_DIR = join(TARGET_DIR, 'csv')
const INDEX_NAME = 'market-csv-index.js'
const INDEX_PATH = join(TARGET_DIR, INDEX_NAME)
const LOCK_DIR = join(DATA_DIR, '.generated.lock')
const TEMP_PREFIX = `.tmp-${process.pid}-`

await withGenerateLock(generate)

async function generate() {
  await mkdir(CSV_MODULE_DIR, { recursive: true })
  const files = (await readdir(SOURCE_DIR)).filter((file) => file.endsWith('.csv')).sort()
  const entries = []
  const pending = []

  for (const file of files) {
    const text = await readFile(join(SOURCE_DIR, file), 'utf8')
    const moduleName = `${safeModuleName(file)}.js`
    const finalPath = join(CSV_MODULE_DIR, moduleName)
    const tempPath = join(CSV_MODULE_DIR, `${TEMP_PREFIX}${moduleName}`)
    await writeFile(tempPath, `export default ${JSON.stringify(text)}\n`)
    pending.push([tempPath, finalPath])
    entries.push([file, moduleName])
  }

  for (const [tempPath, finalPath] of pending) {
    await renameWithRetry(tempPath, finalPath)
  }

  const loaderEntries = entries
    .flatMap(([file, moduleName]) => [
      [file, moduleName],
      [`/data/${file}`, moduleName],
      [`/datasets/${file}`, moduleName],
      [`/datasets/${file}.txt`, moduleName],
    ])
    .map(([key, moduleName]) => `${JSON.stringify(key)}:()=>import(${JSON.stringify(`./csv/${moduleName}`)})`)
    .join(',')

  const fileList = JSON.stringify(entries.map(([file]) => file))
  const indexBody = [
    '// Generated by scripts/csv2js.mjs. Do not edit by hand.',
    `const loaders={${loaderEntries}}`,
    `export const marketCsvFiles=${fileList}`,
    'export async function loadMarketCsv(url){const key=normalizeDataUrl(url);const loader=loaders[key]||loaders[fileNameOf(key)];if(!loader)return null;const mod=await loader();return mod.default}',
    'function normalizeDataUrl(url){return String(url??"").split("#",1)[0].split("?",1)[0]}',
    'function fileNameOf(url){return normalizeDataUrl(url).split("/").at(-1)?.replace(/\\.txt$/i,"")??""}',
    '',
  ].join('\n')
  const indexTemp = join(TARGET_DIR, `${TEMP_PREFIX}${INDEX_NAME}`)
  await writeFile(indexTemp, indexBody)
  await renameWithRetry(indexTemp, INDEX_PATH)

  await removeStaleGeneratedFiles(new Set(entries.map(([, moduleName]) => moduleName)))
  await cleanupLegacyTempDirs()
  console.log(`generated ${entries.length} CSV JS modules`)
}

async function removeStaleGeneratedFiles(keep) {
  for (const name of await readdir(CSV_MODULE_DIR)) {
    if (name.startsWith('.tmp-')) {
      await unlink(join(CSV_MODULE_DIR, name)).catch(() => {})
      continue
    }
    if (name.endsWith('.js') && !keep.has(name)) {
      await unlink(join(CSV_MODULE_DIR, name)).catch(() => {})
    }
  }
  for (const name of await readdir(TARGET_DIR)) {
    if (name.startsWith('.tmp-')) await unlink(join(TARGET_DIR, name)).catch(() => {})
  }
}

async function cleanupLegacyTempDirs() {
  const entries = await readdir(DATA_DIR, { withFileTypes: true })
  for (const entry of entries) {
    if (entry.isDirectory() && entry.name.startsWith('.generated-')) {
      await rm(join(DATA_DIR, entry.name), { recursive: true, force: true }).catch(() => {})
    }
  }
}

async function renameWithRetry(from, to) {
  for (let attempt = 0; attempt < 6; attempt += 1) {
    try {
      await rename(from, to)
      return
    } catch (error) {
      const retryable = ['EPERM', 'EBUSY', 'EACCES'].includes(error?.code)
      if (!retryable || attempt === 5) throw error
      await sleep(100 * (attempt + 1))
    }
  }
}

function safeModuleName(file) {
  return file.replace(/[^A-Za-z0-9_$]/g, '_')
}

async function withGenerateLock(task) {
  const deadline = Date.now() + 60000
  while (true) {
    try {
      await mkdir(LOCK_DIR)
      break
    } catch (error) {
      if (error?.code !== 'EEXIST' || Date.now() > deadline) throw error
      await sleep(100)
    }
  }

  try {
    return await task()
  } finally {
    await rm(LOCK_DIR, { recursive: true, force: true })
  }
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms))
}
