const PATTERNS = [
  [/^(\d{4})-盈利预测-收益$/, '该年度卖方一致预期 EPS（元）。预测会被不断修正，看趋势不看绝对值。'],
  [/^(\d{4})-盈利预测-市盈率$/, '按该年度预测盈利算出的市盈率。'],
  [/净流入-净额$/, '资金净流入金额（元）。'],
  [/净流入-净占比$/, '资金净流入占比（%）。'],
]

export function noteForColumn(column) {
  if (COLUMN_NOTES[column]) return COLUMN_NOTES[column]
  for (const [pattern, note] of PATTERNS) if (pattern.test(column)) return note
  return null
}